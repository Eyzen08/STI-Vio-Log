const express=require('express');
const {passwordChange,profile,updateProfile,resendEmail,verifyEmail,requestGoogleEmail,verifyGoogleEmail,googleLink,completeOnboarding}=require('../controllers/accountController');
const router=express.Router();
const avatar=require('../controllers/avatarController');
const {authorizeRoles,requireExactRoles}=require('../middleware/authMiddleware');
const studentOnboarding=requireExactRoles('STUDENT');
const disciplineAdmin=requireExactRoles('DISCIPLINE_ADMIN');
router.get('/avatar',authorizeRoles('DISCIPLINE_ADMIN','DISCIPLINE_OFFICE','DEPARTMENT_HEAD','STUDENT'),avatar.get);
router.patch('/avatar',authorizeRoles('DISCIPLINE_ADMIN','DISCIPLINE_OFFICE','DEPARTMENT_HEAD','STUDENT'),avatar.select);
router.post('/password-change',passwordChange);
router.post('/student-onboarding/google-email/request',studentOnboarding,requestGoogleEmail);
router.post('/student-onboarding/google-email/verify',studentOnboarding,verifyGoogleEmail);
router.post('/student-onboarding/google-link',studentOnboarding,googleLink);
router.post('/student-onboarding/profile',studentOnboarding,completeOnboarding);
router.get('/admin-profile',disciplineAdmin,profile);
router.patch('/admin-profile',disciplineAdmin,updateProfile);
router.post('/admin-profile/email/resend',disciplineAdmin,resendEmail);
router.post('/admin-profile/email/verify',disciplineAdmin,verifyEmail);
module.exports=router;
