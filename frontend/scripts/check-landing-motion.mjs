const rgb = color => color.match(/[\d.]+/g).slice(0, 3).map(Number)
const luminance = color => rgb(color).map(n => n / 255).map(n => n <= .04045 ? n / 12.92 : ((n + .055) / 1.055) ** 2.4).reduce((sum, n, i) => sum + n * [.2126, .7152, .0722][i], 0)
const contrast = (a, b) => (Math.max(luminance(a), luminance(b)) + .05) / (Math.min(luminance(a), luminance(b)) + .05)
const checkContrast = async locator => {
  const colors = await locator.evaluate(el => { const css = getComputedStyle(el); return { text: el.textContent, foreground: css.color, background: css.backgroundColor } })
  const ratio = contrast(colors.foreground, colors.background)
  assert.ok(ratio >= 4.5, JSON.stringify(colors))
  return ratio
}
